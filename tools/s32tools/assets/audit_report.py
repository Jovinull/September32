"""Rendering the character asset audit as a Markdown document."""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

from s32tools.assets.audit import PackMetrics, compatibility, measure_pack

#: Packs to audit, in the order the report presents them. The core comes first
#: because every other row is measured against it.
AUDIT_PACKS: tuple[str, ...] = (
    "pm_char_a01",
    "pm_char_a02",
    "pm_char_kioshi_haruo",
    "pm_char_sensei",
    "pm_char_hiyori",
    "pm_char_nozomi",
    "pm_char_ryoko_madoka",
    "pm_char_taishiro",
    "pm_char_keiko",
)

CORE = "pm_char_a01"

#: Human names, so the report reads as a document rather than as a dump.
PACK_NAMES: dict[str, str] = {
    "pm_char_a01": "Set A01 — School Ver. (5 free characters)",
    "pm_char_a02": "Set A02 — 3 Outfits (5 free characters)",
    "pm_char_kioshi_haruo": "Kioshi & Haruo",
    "pm_char_sensei": "Sensei Pack",
    "pm_char_hiyori": "Hiyori",
    "pm_char_nozomi": "Nozomi",
    "pm_char_ryoko_madoka": "Ryoko & Madoka",
    "pm_char_taishiro": "Taishiro",
    "pm_char_keiko": "Keiko",
}


def run(vendor_root: Path, packs: tuple[str, ...] = AUDIT_PACKS) -> dict[str, PackMetrics]:
    """Measure every available pack. Missing packs are skipped, not faked."""
    return {
        pack: measure_pack(vendor_root, pack)
        for pack in packs
        if (vendor_root / pack).is_dir()
    }


def to_markdown(metrics: dict[str, PackMetrics]) -> str:
    """Render the audit."""
    core = metrics.get(CORE)
    lines: list[str] = [
        "# Character asset audit",
        "",
        "> Generated by `s32 assets audit`. The numbers are regenerated; the",
        "> **Decision** column is a human judgement and is preserved by hand in",
        "> `docs/production/CHARACTER_ASSET_AUDIT.md`.",
        "",
        f"- Generated: `{datetime.now(UTC).isoformat(timespec='seconds')}`",
        f"- Core pack: `{CORE}`",
        "",
        "## Method",
        "",
        "Every figure below is computed locally from pixel data by",
        "`tools/s32tools/assets/audit.py`. **No image was sent to any external",
        "service**, for analysis or otherwise — see",
        "`docs/legal/AI_AND_ASSETS_POLICY.md`. That constraint is why these are",
        "computable proxies rather than aesthetic judgements:",
        "",
        "| Metric | What it proxies | Why it matters |",
        "| --- | --- | --- |",
        "| `canvas` | Source resolution | Different canvases mean per-pack placement fudging in every scene. |",
        "| `content top/bottom` | Framing | The single biggest cause of a cast that looks pasted together. |",
        "| `head ratio` | Head-to-body proportion | What makes a stylised cast read as one style. |",
        "| `edges` | Line weight | A heavier-lined pack scores visibly higher. |",
        "| `sat` / `val` | Colour treatment | Packs that disagree here will not share a background without grading. |",
        "",
        "What this method **cannot** tell you: whether two characters look like",
        "they belong in the same school, apparent age, or presentation. Those are",
        "open questions for a human (see `docs/canon/OPEN_QUESTIONS.md`).",
        "",
        "## Measurements",
        "",
        "| Pack | Sprites | Canvas | content top | content bottom | head ratio | edges | sat | val |",
        "| --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]

    for pack, m in metrics.items():
        canvas = ", ".join(m.canvas_sizes) or "—"
        lines.append(
            f"| `{pack}` | {m.sprite_count} | {canvas} | {m.content_top:.3f} | "
            f"{m.content_bottom:.3f} | {m.head_width_ratio:.3f} | {m.edge_density:.3f} | "
            f"{m.saturation:.3f} | {m.value:.3f} |"
        )

    lines += ["", "## Compatibility with the core", ""]
    if core is None:
        lines.append("Core pack not installed; run `s32 assets fetch --group characters`.")
        return "\n".join(lines)

    lines += ["| Pack | Score | Notes |", "| --- | ---: | --- |"]
    for pack, m in metrics.items():
        if pack == CORE:
            lines.append(f"| `{pack}` | 10.0 | core |")
            continue
        score, notes = compatibility(core, m)
        note_text = "<br>".join(notes) if notes else "no measurable drift"
        lines.append(f"| `{pack}` | {score} | {note_text} |")

    lines += ["", "## Contents", "", "| Pack | Characters | Outfits per character |", "| --- | --- | --- |"]
    for pack, m in metrics.items():
        if not m.characters:
            lines.append(f"| `{pack}` | (filenames do not follow `character_outfit_expression`) | — |")
            continue
        outfits = "; ".join(f"`{c}`: {', '.join(o)}" for c, o in m.outfits.items())
        lines.append(f"| `{pack}` | {', '.join(m.characters)} | {outfits} |")

    lines.append("")
    return "\n".join(lines)
