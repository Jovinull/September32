"""Generating every credit surface from the asset manifest.

Four things have to agree: ``CREDITS.md``, ``THIRD_PARTY_NOTICES.md``, the plain
text file that ships beside the built game, and the in-game Credits screen.
Maintaining four lists by hand guarantees they diverge, and the one that
diverges is always the one an artist reads.

So all four are generated from ``assets/catalog/assets.toml`` and CI fails if
they are stale. Adding an asset means editing the manifest; the credits follow.

Assets whose licence does not require attribution are still credited, marked as
a courtesy rather than an obligation. Crediting someone who did not ask to be
credited costs nothing; failing to credit someone who did is a real problem.
"""

from __future__ import annotations

from pathlib import Path

from s32tools.assets.manifest import AssetEntry, Manifest

#: Credit section order and headings, matching the in-game screen.
SECTIONS: tuple[tuple[str, str], ...] = (
    ("character", "Character Art"),
    ("background", "Background Art"),
    ("music", "Music"),
    ("sfx", "Sound"),
    ("ui", "UI and Icons"),
    ("prop", "UI and Icons"),
    ("font", "Fonts"),
    ("software", "Third-Party Software"),
)

_GENERATED_WARNING = (
    "<!-- GENERATED FILE — do not edit.\n"
    "     Source of truth: assets/catalog/assets.toml\n"
    "     Regenerate:      s32 assets credits\n"
    "     CI fails if this file is out of date. -->"
)


def _grouped(manifest: Manifest) -> dict[str, list[AssetEntry]]:
    """Group entries by display section, preserving the section order."""
    groups: dict[str, list[AssetEntry]] = {}
    for asset_type, heading in SECTIONS:
        for entry in manifest.by_type(asset_type):
            groups.setdefault(heading, []).append(entry)
    return groups


def credits_markdown(manifest: Manifest) -> str:
    """Render ``CREDITS.md``."""
    lines = [
        _GENERATED_WARNING,
        "",
        "# Credits",
        "",
        "September 32 is built on work by other people. This page lists all of it.",
        "",
        "## Development",
        "",
        "- Design, writing, engineering — the September 32 project authors",
        "",
    ]

    for heading, entries in _grouped(manifest).items():
        lines += [f"## {heading}", ""]
        for entry in entries:
            required = "" if entry.attribution_required else "  _(credit given as a courtesy; not required by the licence)_"
            lines.append(f"- **{entry.name}** — {entry.author}")
            lines.append(f"  - Licence: {entry.license_name}")
            lines.append(f"  - Source: <{entry.source_page}>{required}")
        lines.append("")

    lines += [
        "## A note on how these are used",
        "",
        "Third-party assets are not redistributed by this repository. They are",
        "fetched from their original sources by `s32 assets fetch` onto each",
        "developer's own machine, and appear only inside a built game where the",
        "licence permits it. Each asset's terms are recorded in full in",
        "`assets/catalog/assets.toml`, with the evidence in `assets/evidence/`.",
        "",
        "No asset in this project was generated by AI, and no third-party asset",
        "has been sent to an AI service for analysis, editing or training. See",
        "`docs/legal/AI_AND_ASSETS_POLICY.md`.",
        "",
    ]
    return "\n".join(lines)


def _last_verified(manifest: Manifest) -> str:
    """Return the most recent ``license_verified`` date in the catalogue.

    This replaced a ``datetime.now()`` stamp, which made the generated notices
    differ from the committed ones at every midnight and failed the freshness
    gate on content nobody had touched. A gate that cries wolf daily is a gate
    people stop reading.

    It is also the more useful date. "When a script last ran" says nothing about
    a legal notice; ``license_verified`` is the day a human read the terms, it
    is hand-written in the committed catalogue, and it changes exactly when the
    thing it describes changes.
    """
    dates = sorted(entry.license_verified for entry in manifest.entries.values() if entry.license_verified)
    return dates[-1] if dates else "an unrecorded date"


def notices_markdown(manifest: Manifest) -> str:
    """Render ``THIRD_PARTY_NOTICES.md``.

    Distinct from ``CREDITS.md``: credits thank people, notices discharge legal
    obligations. This file reproduces licence names, sources and the exact
    attribution text where one is required.
    """
    lines = [
        _GENERATED_WARNING,
        "",
        "# Third-party notices",
        "",
        f"Generated from `assets/catalog/assets.toml`. Licence terms last read "
        f"by a person on {_last_verified(manifest)}.",
        "",
        "This document lists third-party material used by September 32 and the",
        "terms it is used under. It covers three separate categories that must not",
        "be conflated:",
        "",
        "1. **The engine** — Ren'Py and the components it bundles.",
        "2. **Assets** — art, music and fonts, each under its own licence.",
        "3. **This project's own content**, which is *not* covered here; see",
        "   `/LICENSE`.",
        "",
    ]

    for heading, entries in _grouped(manifest).items():
        lines += [f"## {heading}", ""]
        for entry in entries:
            lines += [
                f"### {entry.name}",
                "",
                f"- **Author:** {entry.author}",
                f"- **Licence:** {entry.license_name}",
                f"- **Licence source:** <{entry.license_source}>",
                f"- **Source page:** <{entry.source_page}>",
                f"- **Terms verified:** {entry.license_verified}",
                f"- **Commercial use:** {'yes' if entry.commercial_use else 'NO'}",
                f"- **Modification:** {'permitted' if entry.modification_allowed else 'NOT permitted'}",
                f"- **Redistribution of the files themselves:** "
                f"{'permitted' if entry.redistribution_allowed else 'NOT permitted'}",
                f"- **Attribution required:** {'yes' if entry.attribution_required else 'no'}",
                "",
            ]
            if entry.required_credit:
                lines += ["Attribution text:", "", "```", entry.required_credit, "```", ""]
            if entry.license_summary.strip():
                lines += ["Recorded terms:", "", "```"]
                lines += entry.license_summary.strip().splitlines()
                lines += ["```", ""]
            if entry.ai_related_terms.strip():
                lines += ["AI-related terms:", "", "```"]
                lines += entry.ai_related_terms.strip().splitlines()
                lines += ["```", ""]
    return "\n".join(lines)


def credits_text(manifest: Manifest) -> str:
    """Render the plain-text credits that ship beside the built game."""
    lines = [
        "SEPTEMBER 32",
        "Credits",
        "=" * 40,
        "",
        "DEVELOPMENT",
        "  Design, writing, engineering - the September 32 project authors",
        "",
    ]
    for heading, entries in _grouped(manifest).items():
        lines.append(heading.upper())
        for entry in entries:
            lines.append(f"  {entry.credit_line()}")
            lines.append(f"    {entry.source_page}")
        lines.append("")
    lines += [
        "Full terms for every item above are recorded in",
        "THIRD_PARTY_NOTICES.md, distributed with this game.",
        "",
    ]
    return "\n".join(lines)


def credits_rpy(manifest: Manifest) -> str:
    """Render the Ren'Py data file backing the in-game Credits screen.

    Generated as *data*, not as a screen: the screen's layout lives in
    ``game/screens/credits.rpy`` where a designer can work on it, and only the
    content comes from the manifest.
    """
    lines = [
        "# GENERATED FILE - do not edit.",
        "# Source of truth: assets/catalog/assets.toml",
        "# Regenerate:      s32 assets credits",
        "#",
        "# Consumed by game/screens/credits.rpy, which owns the presentation.",
        "",
        "init python:",
        "",
        "    # (section, [(line, sublabel), ...])",
        "    s32_credits_sections = [",
        '        ("Development", [',
        '            ("Design, writing, engineering", "the September 32 project authors"),',
        "        ]),",
    ]
    for heading, entries in _grouped(manifest).items():
        lines.append(f'        ("{heading}", [')
        for entry in entries:
            credit = entry.credit_line().replace('"', '\\"')
            source = entry.source_page.replace('"', '\\"')
            lines.append(f'            ("{credit}", "{source}"),')
        lines.append("        ]),")
    lines += [
        "    ]",
        "",
        "    # Shown at the foot of the credits screen.",
        "    s32_credits_footer = (",
        '        "No asset in this game was generated by AI. Full licence terms for '
        'every item above are in THIRD_PARTY_NOTICES.md, included with this game."',
        "    )",
        "",
    ]
    return "\n".join(lines)


#: Output path (relative to the repository root) -> renderer.
OUTPUTS: dict[str, str] = {
    "CREDITS.md": "credits_markdown",
    "THIRD_PARTY_NOTICES.md": "notices_markdown",
    "game/credits.txt": "credits_text",
    "game/credits_data.rpy": "credits_rpy",
}


def render(name: str, manifest: Manifest) -> str:
    """Render one output by its path key."""
    renderer = globals()[OUTPUTS[name]]
    text: str = renderer(manifest)
    return text


def write_all(repo_root: Path, manifest: Manifest) -> list[Path]:
    """Write every credit surface. Returns the paths written."""
    written = []
    for name in OUTPUTS:
        path = repo_root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(name, manifest), encoding="utf-8")
        written.append(path)
    return written


def check_all(repo_root: Path, manifest: Manifest) -> list[str]:
    """Return the credit files that are missing or out of date."""
    stale = []
    for name in OUTPUTS:
        path = repo_root / name
        expected = render(name, manifest)
        if not path.exists():
            stale.append(f"{name}: missing")
        elif path.read_text(encoding="utf-8") != expected:
            stale.append(f"{name}: out of date")
    return stale
