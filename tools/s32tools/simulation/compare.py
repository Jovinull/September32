"""Comparing two simulation reports.

The milestone question is not "what are the numbers" but "did they move, and in
the direction the design predicted". This renders both runs side by side so a
regression is visible rather than inferred.

Reads the JSON reports rather than re-simulating: a comparison that re-runs the
baseline against changed content is not a comparison.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def load(path: Path) -> dict[str, Any]:
    """Read one simulation report."""
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def _delta(before: float, after: float, *, percent: bool = False) -> str:
    """Render a change with its direction, or a dash when nothing moved."""
    change = after - before
    if abs(change) < 1e-9:
        return "—"
    sign = "+" if change > 0 else ""
    return f"{sign}{change:.1%}" if percent else f"{sign}{change:.2f}"


def to_markdown(
    before: dict[str, Any], after: dict[str, Any], *, label_before: str, label_after: str
) -> str:
    """Render the comparison."""
    lines = [
        "# Simulation: before and after",
        "",
        "> Generated by `s32 compare`. Both runs use the same seed and the same",
        "> number of playthroughs, so the only variable is the content.",
        "",
        f"- **{label_before}**: {before['runs']} runs, seed {before['seed']}",
        f"- **{label_after}**: {after['runs']} runs, seed {after['seed']}",
        "",
        "## Headline",
        "",
        "| | before | after | change |",
        "| --- | ---: | ---: | ---: |",
    ]

    rows: list[tuple[str, Any, Any, str]] = [
        (
            "Storylets in library",
            before["storylets"]["total"],
            after["storylets"]["total"],
            f"+{after['storylets']['total'] - before['storylets']['total']}",
        ),
        (
            "Reachable",
            f"{len(before['storylets']['reachable'])}/{before['storylets']['total']}",
            f"{len(after['storylets']['reachable'])}/{after['storylets']['total']}",
            "",
        ),
        (
            "Dead ends",
            before["dead_ends"]["count"],
            after["dead_ends"]["count"],
            "",
        ),
        (
            "Scenes per run",
            before["averages"]["scenes_per_run"],
            after["averages"]["scenes_per_run"],
            _delta(before["averages"]["scenes_per_run"], after["averages"]["scenes_per_run"]),
        ),
        (
            "Repeated scenes per run",
            before["averages"]["repeats_per_run"],
            after["averages"]["repeats_per_run"],
            _delta(before["averages"]["repeats_per_run"], after["averages"]["repeats_per_run"]),
        ),
    ]

    # Unique scenes is the number the pacing question actually turns on.
    for name, source in (("before", before), ("after", after)):
        source["_unique"] = round(
            source["averages"]["scenes_per_run"] - source["averages"]["repeats_per_run"], 2
        )
        _ = name
    rows.append(
        (
            "**Unique** scenes per run",
            before["_unique"],
            after["_unique"],
            _delta(before["_unique"], after["_unique"]),
        )
    )

    for name, was, now, change in rows:
        lines.append(f"| {name} | {was} | {now} | {change} |")

    lines += [
        "",
        "## Content mix",
        "",
        "| Tag | before | after | change |",
        "| --- | ---: | ---: | ---: |",
    ]
    tags = sorted(set(before["content_mix"]) | set(after["content_mix"]))
    for tag in tags:
        was = before["content_mix"].get(tag, 0.0)
        now = after["content_mix"].get(tag, 0.0)
        lines.append(f"| {tag} | {was:.1%} | {now:.1%} | {_delta(was, now, percent=True)} |")

    lines += ["", "## Most played", "", "| Storylet | before | after |", "| --- | ---: | ---: |"]
    counts_before = before["storylets"]["play_counts"]
    counts_after = after["storylets"]["play_counts"]
    for storylet in sorted(counts_after, key=lambda s: -counts_after[s]):
        lines.append(
            f"| `{storylet}` | {counts_before.get(storylet, 0):,} | {counts_after[storylet]:,} |"
        )

    lines += [
        "",
        "## Share taken by the single most played scene",
        "",
    ]
    for name, source in ((label_before, before), (label_after, after)):
        counts = source["storylets"]["play_counts"]
        total = sum(counts.values()) or 1
        top = max(counts, key=lambda s: counts[s])
        lines.append(f"- **{name}**: `{top}` — {counts[top] / total:.1%} of everything played")

    lines += [
        "",
        "## Character encounter rate",
        "",
        "| Character | before | after |",
        "| --- | ---: | ---: |",
    ]
    characters = sorted(
        set(before["characters"]["encounter_rate"]) | set(after["characters"]["encounter_rate"])
    )
    for character in characters:
        was = before["characters"]["encounter_rate"].get(character, 0.0)
        now = after["characters"]["encounter_rate"].get(character, 0.0)
        lines.append(f"| `{character}` | {was:.1%} | {now:.1%} |")

    lines += [
        "",
        "## Knowledge acquisition",
        "",
        "| Fact | before | after |",
        "| --- | ---: | ---: |",
    ]
    facts = sorted(
        set(before["knowledge"]["acquisition_rate"]) | set(after["knowledge"]["acquisition_rate"])
    )
    for fact in facts:
        was = before["knowledge"]["acquisition_rate"].get(fact, 0.0)
        now = after["knowledge"]["acquisition_rate"].get(fact, 0.0)
        lines.append(f"| `{fact}` | {was:.1%} | {now:.1%} |")

    lines.append("")
    return "\n".join(lines)
