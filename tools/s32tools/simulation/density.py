"""Narrative candidate density: how often the director actually had a choice.

Milestone 1 measured 15 storylets and found the library healthy by every metric
it had -- and then found, by instrumenting the moment of selection, that 92.7%
of the time exactly one storylet was eligible. A director choosing between one
option is not choosing.

Two numbers carry this, and they are not the same number:

**Eligible count.** How many storylets fit the world at all.

**Top priority tier size.** How many of those shared the highest priority.
Priority is a hard tier (:meth:`NarrativeDirector.select`), so only this group
competes. Five eligible storylets with one in the top tier still leaves the
weighted draw nothing to draw from, which is why both are reported.
"""

from __future__ import annotations

from collections import Counter
from typing import Any

from s32_engine.types import TIME_SLOTS, ContentLibrary
from s32tools.simulation.simulator import SimulationResult

#: Buckets for the histograms. Anything above the last named bucket is grouped,
#: because the interesting distinction is 1 vs 2 vs "several", not 6 vs 7.
BUCKETS: tuple[int, ...] = (0, 1, 2, 3)
OVERFLOW = "4+"


def _histogram(counter: Counter[int]) -> dict[str, float]:
    """Return a bucketed distribution as shares of the total."""
    total = sum(counter.values()) or 1
    out: dict[str, float] = {}
    for bucket in BUCKETS:
        out[str(bucket)] = round(counter.get(bucket, 0) / total, 4)
    overflow = sum(count for size, count in counter.items() if size > BUCKETS[-1])
    out[OVERFLOW] = round(overflow / total, 4)
    return out


def to_dict(result: SimulationResult, library: ContentLibrary) -> dict[str, Any]:
    """Return the machine-readable density payload."""
    moments = sum(result.eligible_hist.values())
    singleton = result.eligible_hist.get(1, 0)
    tier_moments = sum(result.tier_hist.values()) or 1
    tier_multi = sum(count for size, count in result.tier_hist.items() if size >= 2)

    cells: dict[str, dict[str, Any]] = {}
    for cell, visits in result.cell_moments.items():
        location, _, slot = cell.partition("|")
        cells[cell] = {
            "location": location,
            "time_slot": slot,
            "moments": visits,
            "mean_eligible": round(result.cell_eligible.get(cell, 0) / visits, 2),
            "multi_rate": round(result.cell_multi.get(cell, 0) / visits, 4),
        }

    # Two denominators, both wanted. Milestone 1 measured singletons only over
    # moments that produced a scene, which is the number an author feels; this
    # tool sees the empty moments too, which is the number that explains the
    # wandering. Reporting one without the other invites a false comparison.
    productive = moments - result.eligible_hist.get(0, 0)

    return {
        "selection_moments": moments,
        "productive_moments": productive,
        "empty_rate": round(result.eligible_hist.get(0, 0) / moments, 4) if moments else 0.0,
        "singleton_when_any": round(singleton / productive, 4) if productive else 0.0,
        "eligible_distribution": _histogram(result.eligible_hist),
        "tier_distribution": _histogram(result.tier_hist),
        "singleton_eligible_rate": round(singleton / moments, 4) if moments else 0.0,
        "tier_multi_rate": round(tier_multi / tier_moments, 4),
        "authored_cells": _authored(library),
        "cells": dict(sorted(cells.items())),
    }


def _authored(library: ContentLibrary) -> dict[str, int]:
    """Return, per cell, how many storylets could apply there ignoring state.

    A ceiling rather than an observation: it counts what a writer put in the
    library, which is the number an author can act on directly.
    """
    out: Counter[str] = Counter()
    locations = sorted(library.locations)
    for storylet in library.storylets.values():
        places = [storylet.location] if storylet.location else locations
        slots = storylet.time_slots or TIME_SLOTS
        for place in places:
            for slot in slots:
                out[f"{place}|{slot}"] += 1
    return dict(sorted(out.items()))


def to_markdown(result: SimulationResult, library: ContentLibrary) -> str:
    """Return the human-readable density report."""
    payload = to_dict(result, library)
    lines = [
        "# Narrative candidate density",
        "",
        "> Generated by `s32 density`. The question is not how much content",
        "> exists but how often the director was given a choice between any of",
        "> it.",
        "",
        f"- Runs: {result.runs}, seed {result.seed}",
        f"- Selection moments: {payload['selection_moments']:,}",
        "",
        "## Eligible candidates per selection",
        "",
        "| Candidates | Share |",
        "| --- | ---: |",
    ]
    for bucket, share in payload["eligible_distribution"].items():
        lines.append(f"| {bucket} | {share:.1%} |")

    lines += [
        "",
        "## Top priority tier size",
        "",
        "Only this group competes in the weighted draw. A tier of one means the",
        "draw is a formality.",
        "",
        "| Tier size | Share |",
        "| --- | ---: |",
    ]
    for bucket, share in payload["tier_distribution"].items():
        lines.append(f"| {bucket} | {share:.1%} |")

    lines += [
        "",
        "## Headline",
        "",
        f"- Nothing eligible anywhere: **{payload['empty_rate']:.1%}** of moments",
        "- Exactly one eligible candidate: "
        f"**{payload['singleton_when_any']:.1%}** of the "
        f"{payload['productive_moments']:,} moments that had anything at all "
        f"({payload['singleton_eligible_rate']:.1%} of all moments)",
        f"- Top tier held two or more: **{payload['tier_multi_rate']:.1%}**",
        "",
        "## Location x time slot",
        "",
        "`authored` is how many storylets name that cell at all; `mean` is the",
        "average number actually eligible when the player was there; `visits`",
        "is how many selection moments happened there.",
        "",
    ]
    lines += _matrix(payload, library)
    return "\n".join(lines) + "\n"


def _matrix(payload: dict[str, Any], library: ContentLibrary) -> list[str]:
    """Render the location x time-slot table."""
    locations = sorted(library.locations)
    header = "| Location | " + " | ".join(s.replace("_", " ") for s in TIME_SLOTS) + " |"
    rule = "| --- | " + " | ".join("---:" for _ in TIME_SLOTS) + " |"
    rows = [header, rule]
    for location in locations:
        cells = []
        for slot in TIME_SLOTS:
            key = f"{location}|{slot}"
            authored = payload["authored_cells"].get(key, 0)
            observed = payload["cells"].get(key)
            if observed is None:
                cells.append(f"{authored} / -")
            else:
                mean = observed["mean_eligible"]
                cells.append(f"{authored} / {mean:.1f} ({observed['moments']})")
        rows.append(f"| `{location}` | " + " | ".join(cells) + " |")
    rows += [
        "",
        "Read each cell as `authored / mean eligible (visits)`. A dash means the",
        "player never stood there at that hour in any run.",
    ]
    return rows
