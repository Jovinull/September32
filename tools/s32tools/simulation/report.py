"""Rendering simulation results as JSON and Markdown.

JSON is for other tools and for diffing two runs. Markdown is for the human who
has to decide what to write next; it leads with the findings that demand action
(unreachable content, dead ends) rather than with statistics.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from typing import Any

from s32_engine.types import ContentLibrary
from s32tools.simulation import density
from s32tools.simulation.simulator import SimulationResult


def to_dict(result: SimulationResult, library: ContentLibrary) -> dict[str, Any]:
    """Return the machine-readable form of a simulation result."""
    total_plays = sum(result.play_counts.values()) or 1
    return {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "runs": result.runs,
        "seed": result.seed,
        "profiles": result.profiles,
        "storylets": {
            "total": result.library_size,
            "reachable": sorted(result.reachable),
            "unreachable": sorted(result.unreachable),
            "play_counts": dict(sorted(result.play_counts.items())),
        },
        "anchors": {
            "total": len(library.anchors),
            "reached": dict(sorted(result.anchor_counts.items())),
            "unreached": sorted(set(library.anchors) - set(result.anchor_counts)),
        },
        "knowledge": {
            "acquisition_rate": {
                fact: round(count / result.runs, 4)
                for fact, count in sorted(result.knowledge_counts.items())
            },
            "never_acquired": sorted(set(library.knowledge) - set(result.knowledge_counts)),
        },
        "characters": {
            "encounter_rate": {
                char: round(count / result.runs, 4)
                for char, count in sorted(result.character_counts.items())
            }
        },
        "content_mix": {
            tag: round(count / total_plays, 4) for tag, count in sorted(result.tag_counts.items())
        },
        "phases_reached": dict(sorted(result.phase_counts.items())),
        "averages": {
            "scenes_per_run": round(result.average_scenes, 2),
            "days_per_run": round(result.average_days, 2),
            "repeats_per_run": round(result.average_repeats, 2),
        },
        "dead_ends": {
            "count": result.dead_ends,
            "rate": round(result.dead_ends / result.runs, 4) if result.runs else 0.0,
            "examples": [
                {
                    "seed": run.seed,
                    "profile": run.profile,
                    "stuck_at": run.dead_end_at,
                    "played": run.storylets_played,
                }
                for run in result.dead_end_examples
            ],
        },
        "rare_states": [{"storylet": sid, "plays": n} for sid, n in result.rare_storylets],
        # Embedded rather than written alongside, so `s32 compare` can diff the
        # density of two runs from the one file it already reads.
        "density": density.to_dict(result, library),
        "relationship_ranges": {k: list(v) for k, v in result.relationship_ranges.items()},
    }


def to_markdown(  # noqa: PLR0912, PLR0915 - a linear document builder; splitting scatters the layout
    result: SimulationResult, library: ContentLibrary
) -> str:
    """Return the human-readable report."""
    payload = to_dict(result, library)
    lines: list[str] = [
        "# Simulation report",
        "",
        "> Generated by `s32 simulate`. Do not edit; re-run the command.",
        "",
        f"- Generated: `{payload['generated_at']}`",
        f"- Runs: **{result.runs}**, base seed `{result.seed}`",
        f"- Profiles: {', '.join(result.profiles)}",
        f"- Storylets in library: **{result.library_size}**",
        "",
    ]

    lines += ["## Findings", ""]
    findings: list[str] = []

    if result.unreachable:
        findings.append(
            f"**{len(result.unreachable)} unreachable storylet(s)** — no simulated "
            "playthrough reached the state they require."
        )
    unreached_anchors = payload["anchors"]["unreached"]
    if unreached_anchors:
        findings.append(
            f"**{len(unreached_anchors)} anchor(s) never reached**: {', '.join(unreached_anchors)}"
        )
    never = payload["knowledge"]["never_acquired"]
    if never:
        findings.append(f"**{len(never)} knowledge fact(s) never acquired**: {', '.join(never)}")
    if result.dead_ends:
        findings.append(
            f"**{result.dead_ends} dead end(s)** ({payload['dead_ends']['rate']:.1%} of runs) — "
            "the run ran out of eligible content before finishing."
        )

    lines += [f"- {f}" for f in findings] if findings else ["Nothing to flag."]
    lines.append("")

    if result.unreachable:
        lines += ["## Unreachable storylets", ""]
        for sid in sorted(result.unreachable):
            storylet = library.storylets[sid]
            lines += [f"### `{sid}`", ""]
            if storylet.summary:
                lines += [f"{storylet.summary}", ""]
            lines.append("```")
            lines.append("requires:")
            for req in storylet.requirements or ("(none)",):
                lines.append(f"    {req}")
            if storylet.location:
                lines.append(f"    location == {storylet.location}")
            if storylet.time_slots:
                lines.append(f"    time_slot in {', '.join(storylet.time_slots)}")
            if storylet.phases:
                lines.append(f"    phase in {', '.join(storylet.phases)}")
            for blocker in storylet.blockers:
                lines.append(f"blocked by: {blocker}")
            lines.append("")
            lines.append(f"No simulated playthrough ({result.runs} runs) reached this state.")
            lines.append("```")
            lines.append("")

    if result.dead_end_examples:
        lines += ["## Dead-end examples", ""]
        for run in result.dead_end_examples:
            lines += [
                f"- seed `{run.seed}`, profile `{run.profile}` — stuck at {run.dead_end_at} "
                f"after {len(run.storylets_played)} scene(s)",
            ]
        lines.append("")
        lines.append("Reproduce with `s32 simulate --runs 1 --seed <seed> --profile <profile>`.")
        lines.append("")

    lines += [
        "## Averages",
        "",
        "| Metric | Value |",
        "| --- | ---: |",
        f"| Scenes per run | {payload['averages']['scenes_per_run']} |",
        f"| In-fiction days per run | {payload['averages']['days_per_run']} |",
        f"| Repeated scenes per run | {payload['averages']['repeats_per_run']} |",
        "",
        "## Storylet play counts",
        "",
        "| Storylet | Plays | Runs containing it |",
        "| --- | ---: | ---: |",
    ]
    for sid in sorted(library.storylets):
        plays = result.play_counts.get(sid, 0)
        lines.append(f"| `{sid}` | {plays} | {plays / result.runs:.2f} |")
    lines.append("")

    lines += [
        "## Content mix",
        "",
        "Share of all played scenes carrying each tag.",
        "",
        "| Tag | Share |",
        "| --- | ---: |",
    ]
    for tag, share in sorted(payload["content_mix"].items(), key=lambda kv: -kv[1]):
        lines.append(f"| {tag} | {share:.1%} |")
    lines.append("")

    lines += ["## Knowledge acquisition", "", "| Fact | Runs acquiring it |", "| --- | ---: |"]
    for fact in sorted(library.knowledge):
        rate = payload["knowledge"]["acquisition_rate"].get(fact, 0.0)
        lines.append(f"| `{fact}` | {rate:.1%} |")
    lines.append("")

    lines += [
        "## Character encounter rate",
        "",
        "| Character | Runs with a scene | ",
        "| --- | ---: |",
    ]
    for char in sorted(library.characters):
        rate = payload["characters"]["encounter_rate"].get(char, 0.0)
        lines.append(f"| `{char}` | {rate:.1%} |")
    lines.append("")

    lines += ["## Final phase distribution", "", "| Phase | Runs |", "| --- | ---: |"]
    for phase, count in payload["phases_reached"].items():
        lines.append(f"| {phase} | {count} |")
    lines.append("")

    lines += [
        "## Relationship ranges",
        "",
        "Minimum and maximum observed across all runs. A range of `0-0` means "
        "nothing in the content moves that axis yet.",
        "",
        "| Pair / axis | Min | Max |",
        "| --- | ---: | ---: |",
    ]
    for key, (low, high) in result.relationship_ranges.items():
        if high > 0:
            lines.append(f"| `{key}` | {low} | {high} |")
    lines.append("")

    return "\n".join(lines)


def to_json(result: SimulationResult, library: ContentLibrary) -> str:
    """Return the JSON report text."""
    return json.dumps(to_dict(result, library), indent=2, ensure_ascii=False) + "\n"
